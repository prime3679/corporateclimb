# ---------------------------------------------------------------------------
# Render
# ---------------------------------------------------------------------------


def render(name: str, tpl: list[str]) -> Image.Image:
    im = Image.new('RGBA', (CELL, CELL), (0, 0, 0, 0))
    body: set[tuple[int, int]] = set()
    for y, ln in enumerate(tpl):
        for x, ch in enumerate(ln):
            if ch == '.':
                continue
            body.add((x, y))
            im.putpixel((x, y), PALETTE[ch])
    for x, y in body:
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if (nx, ny) in body:
                continue
            if not (0 <= nx < CELL and 0 <= ny < CELL):
                raise SystemExit(f'{name}: outline leaves the cell at ({nx}, {ny})')
            im.putpixel((nx, ny), INK)
    return im


def build_sheet() -> tuple[Image.Image, dict[str, tuple[int, int]]]:
    names = list(ICONS)
    nrows = (len(names) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (COLS * STRIDE, nrows * STRIDE), (0, 0, 0, 0))
    index: dict[str, tuple[int, int]] = {}
    for i, name in enumerate(names):
        col, row = i % COLS, i // COLS
        sheet.alpha_composite(render(name, ICONS[name]), (col * STRIDE + PAD, row * STRIDE + PAD))
        index[name] = (col, row)
    return sheet, index


def emit_ts(index: dict[str, tuple[int, int]], sheet: Image.Image) -> str:
    lines = [
        '// Generated by scripts/gen_office_icons.py — do not edit by hand.',
        '// Cell = 16×16 art in an 18×18 slot (1px transparent gutter). Keys are',
        '// perk / Status Symbol ids plus `locked`; PixelIcon reads them.',
        '',
        "export const ICON_SHEET_URL = '/office/icons.png'",
        f'export const ICON_CELL = {CELL}',
        f'export const ICON_PAD = {PAD}',
        f'export const ICON_STRIDE = {STRIDE}',
        f'export const ICON_SHEET_W = {sheet.width}',
        f'export const ICON_SHEET_H = {sheet.height}',
        '',
        'export const ICON_ATLAS = {',
    ]
    for name, (col, row) in index.items():
        lines.append(f'  {name}: [{col}, {row}],')
    lines.append('} as const satisfies Record<string, readonly [number, number]>')
    lines.append('')
    lines.append('export type IconName = keyof typeof ICON_ATLAS')
    lines.append('')
    return '\n'.join(lines)


def main() -> None:
    sheet, index = build_sheet()
    OUT_PNG.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT_PNG, optimize=True)
    OUT_TS.write_text(emit_ts(index, sheet))
    print(f'wrote {OUT_PNG.relative_to(ROOT)} ({sheet.width}×{sheet.height}, {len(index)} icons)')
    print(f'wrote {OUT_TS.relative_to(ROOT)}')
    if '--preview' in sys.argv:
        # Codex slot surface behind every cell so the ink outline reads as it will in-game.
        bg = Image.new('RGBA', sheet.size, (42, 48, 66, 255))
        bg.alpha_composite(sheet)
        big = bg.resize((sheet.width * 4, sheet.height * 4), Image.NEAREST)
        big.save('/tmp/office_icons_preview.png')
        print('wrote /tmp/office_icons_preview.png')


if __name__ == '__main__':
    main()
