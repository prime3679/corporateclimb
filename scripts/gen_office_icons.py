def rows(block: str) -> list[str]:
    out = [ln.strip() for ln in block.strip('\n').splitlines()]
    return [ln for ln in out if ln]


# ---------------------------------------------------------------------------
# Glyphs — keyed by perk / relic id. Order here is sheet order.
# ---------------------------------------------------------------------------

ICONS: dict[str, list[str]] = {}


def icon(name: str, block: str) -> None:
    tpl = rows(block)
    if len(tpl) != CELL or any(len(ln) != CELL for ln in tpl):
        raise SystemExit(f'{name}: template must be {CELL}×{CELL}')
    bad = {ch for ln in tpl for ch in ln if ch != '.' and ch not in PALETTE}
    if bad:
        raise SystemExit(f'{name}: unknown palette letters {sorted(bad)}')
    ICONS[name] = tpl


