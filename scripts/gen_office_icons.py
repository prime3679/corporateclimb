#!/usr/bin/env python3
"""Codex icon family — hand-authored 16×16 pixel glyphs, one sheet.

Output: public/office/icons.png (RGBA) plus src/ui/iconAtlas.ts, the
name → cell index that `PixelIcon` reads. One cell per perk and Status
Symbol (keyed by content id) plus `locked`, the glyph every gated slot
shows before its achievement is earned.

The art language is the Office one (scripts/gen_office_actors.py,
scripts/gen_office_tiles.py): light from the top-left, a lit / base /
shadow ramp per material, one plum ink for the silhouette, no
anti-aliasing, no gradients. Every glyph is an object — a dumbbell, a
shield, a key — never a face or a figure, so the set reads as one family
on the Codex slot and nothing in it is a portrait.

Templates are 16 rows × 16 columns of palette letters ('.' transparent).
The body is drawn inside the 14×14 interior; the generator inks the
4-neighbour outline into the outer ring and refuses a template whose
outline would leave the cell.

Cells are stored on an 18px stride with a 1px transparent gutter so a
scaled `background-position` never samples the neighbouring glyph.

Usage:
    python3 scripts/gen_office_icons.py            # write sheet + atlas
    python3 scripts/gen_office_icons.py --preview  # also dump a 4× contact sheet to /tmp
"""

